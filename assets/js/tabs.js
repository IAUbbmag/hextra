function selectHextraTab(button) {
  // set parent tabs to unselected
  const tabs = Array.from(button.parentElement.querySelectorAll('.hextra-tabs-toggle'));
  tabs.map(tab => tab.dataset.state = '');

  // set current tab to selected
  button.dataset.state = 'selected';

  // set all panels to unselected
  const panelsContainer = button.parentElement.parentElement.nextElementSibling;
  Array.from(panelsContainer.children).forEach(function (panel) {
    panel.dataset.state = '';
  });

  const panelId = button.getAttribute('aria-controls');
  const panel = panelsContainer.querySelector(`#${panelId}`);
  panel.dataset.state = 'selected';
}

document.querySelectorAll('.hextra-tabs-toggle').forEach(function (button) {
  button.addEventListener('click', function (e) {
    selectHextraTab(e.currentTarget);
  });
});

// When the URL hash points at an element inside a hidden tab panel
// (e.g. /references/#<article> for a later issue), select that tab first
// so the target becomes visible.
function revealHashTarget() {
  const raw = window.location.hash.substring(1);
  if (!raw) return;
  // Ids generated by `urlize` may be stored percent-encoded (upper-case hex),
  // while links may use lower-case hex or plain text, so try each form.
  let decoded = raw;
  try { decoded = decodeURIComponent(raw); } catch (e) {}
  const target = [raw, decoded, encodeURIComponent(decoded)]
    .map(function (id) { return document.getElementById(id); })
    .find(Boolean);
  if (!target) return;
  const panel = target.closest('.hextra-tabs-panel');
  if (!panel) return;
  const panelsContainer = panel.parentElement;
  const toggleBar = panelsContainer.previousElementSibling;
  const button = toggleBar && toggleBar.querySelector(`.hextra-tabs-toggle[aria-controls="${panel.id}"]`);
  if (button && panel.dataset.state !== 'selected') selectHextraTab(button);
  if (target.tagName === 'DETAILS') target.open = true;
  target.scrollIntoView({ block: 'start' });
}

revealHashTarget();
// Run after other hashchange handlers (e.g. the details shortcode closes all <details> first).
window.addEventListener('hashchange', function () { setTimeout(revealHashTarget, 0); });
